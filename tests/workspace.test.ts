test('cards, boards, shared undo and external edits preserve file identity and content',async t => {
  const f=await fixture(); const w=await Workspace.open(f.root,f.cache);
  t.after(async () => { w.close(); await fs.rm(f.folder,{recursive:true,force:true}); });
  await w.createFolder('','Ideas');
  const boardNow=()=>w.snapshot().boards.find(b=>b.folder==='Ideas')!;
  const undo=new UndoHistory();
  const created=await w.create('Ideas','untitled',20,30); undo.record('Create',created.edits);
  const card=await w.card('Ideas/untitled.md');
  const content='# A thought\n\nSome **formatted** text.\n';
  const edited=await w.saveCard(card.path,content,card.revision); undo.record('Write',edited.edits);
  const board=structuredClone(boardNow()); board.cards[0].x=500;
  const moved=await w.saveBoard(board,board.revision); undo.record('Move',moved.edits);
  await undo.travel(false,changes => w.write(changes));
  assert.equal(boardNow().cards[0].x,20);
  assert.equal((await w.card(card.path)).body,content);
  await undo.travel(false,changes => w.write(changes));
  assert.equal((await w.card(card.path)).body,'');
  await undo.travel(true,changes => w.write(changes));
  assert.equal((await w.card(card.path)).body,content);
  const second=await w.create('Ideas','untitled',500,30);
  assert.equal(second.snapshot.cards.length,2); assert.ok(second.snapshot.cards.some(c => c.path === 'Ideas/untitled_1.md'));
  assert.equal('body' in second.snapshot.cards[0],false,'metadata snapshots do not transfer note bodies');
  await fs.rename(join(f.root,card.path),join(f.root,'Ideas/renamed.md'));
  await w.refresh(card.path); await w.refresh('Ideas/renamed.md');
  const renamed=await w.card('Ideas/renamed.md'); assert.equal(renamed.id,card.id);
  assert.equal(boardNow().cards[0].cardId,renamed.id);
  await fs.writeFile(join(f.root,'Ideas/renamed.md'),await w.read('Ideas/renamed.md')+'\nExternal edit');
  await assert.rejects(() => w.saveCard('Ideas/renamed.md','stale app edit',renamed.revision),/External changes/);
  assert.match(await w.read('Ideas/renamed.md'),/External edit/);
  // A stale undo never removes an external edit or drops its undo entry.
  await assert.rejects(() => undo.travel(false,changes => w.write(changes)),/External changes/);
  assert.equal(undo.past.at(-1)?.label,'Write');
});
